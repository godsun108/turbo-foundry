"""Local-only capability gate for fictional approval and worker operations.

Secrets are generated by secrets.token_urlsafe; only SHA-256 digests persist.
This is NOT production identity authentication or a hosted access boundary.
"""
import hashlib
import secrets
import sqlite3

from .offline_workflow_runner import OfflineWorkflowRunner, RunnerDenied, _key
from .claimed_mock_executor import ClaimedMockExecutor


class CapabilityDenied(ValueError):
    pass


def _digest(token):
    if not isinstance(token,str) or not 32 <= len(token) <= 256:
        raise CapabilityDenied("invalid capability")
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


class OfflineCapabilityGate:
    """Trusted local test harness; issuance is an administrative fixture operation."""

    def __init__(self, runner):
        if not isinstance(runner,OfflineWorkflowRunner):
            raise CapabilityDenied("offline runner required")
        self.runner=runner
        self.executor=ClaimedMockExecutor(runner)
        with sqlite3.connect(runner.db_path) as db:
            db.execute("""CREATE TABLE IF NOT EXISTS offline_capabilities(
                digest TEXT PRIMARY KEY, tenant TEXT NOT NULL,
                role TEXT NOT NULL CHECK(role IN ('reviewer','worker')),
                revoked INTEGER NOT NULL DEFAULT 0,
                used INTEGER NOT NULL DEFAULT 0)""")

    def issue_fixture(self, *, tenant, role):
        """ONLY trusted fixture setup may call this. Not an API or self-service."""
        if not _key(tenant) or role not in ("reviewer","worker"):
            raise CapabilityDenied("invalid scope")
        token=secrets.token_urlsafe(32)
        with sqlite3.connect(self.runner.db_path) as db:
            db.execute("""INSERT INTO offline_capabilities
                (digest,tenant,role) VALUES(?,?,?)""",
                (_digest(token),tenant,role))
        return token

    def revoke_fixture(self, *, token):
        with sqlite3.connect(self.runner.db_path) as db:
            return db.execute("""UPDATE offline_capabilities SET revoked=1
                WHERE digest=?""",(_digest(token),)).rowcount==1

    def approve(self, *, token, tenant, job_id):
        if not _key(tenant) or not _key(job_id):
            raise CapabilityDenied("invalid scope")
        with sqlite3.connect(self.runner.db_path,timeout=10) as db:
            db.execute("BEGIN IMMEDIATE")
            allowed=db.execute("""UPDATE offline_capabilities SET used=1
                WHERE digest=? AND tenant=? AND role='reviewer'
                AND revoked=0 AND used=0""",(_digest(token),tenant)).rowcount
            if allowed!=1:
                raise CapabilityDenied("review capability denied")
            updated=db.execute("""UPDATE offline_jobs SET state='queued'
                WHERE tenant=? AND job_id=? AND state='awaiting_review'""",
                (tenant,job_id)).rowcount
            if updated!=1:
                raise CapabilityDenied("no pending reviewed job")
            self.runner._audit(db,tenant,job_id,"queued","capability_review_mock")
        return True

    def execute(self, *, token, tenant, job_id, now):
        if not _key(tenant) or not _key(job_id):
            raise CapabilityDenied("invalid scope")
        digest=_digest(token)
        with sqlite3.connect(self.runner.db_path,timeout=10) as db:
            db.execute("BEGIN IMMEDIATE")
            permitted=db.execute("""SELECT 1 FROM offline_capabilities
                WHERE digest=? AND tenant=? AND role='worker'
                AND revoked=0""",(digest,tenant)).fetchone()
            if not permitted:
                raise CapabilityDenied("worker capability denied")
        # Worker token is a digest-derived fictional claim identifier, not a
        # provider identity. Authorization checked before the local mock action.
        return self.executor.execute(tenant=tenant,job_id=job_id,
                                     worker_token="cap_"+digest[:40],now=now,
                                     capability_digest=digest)
